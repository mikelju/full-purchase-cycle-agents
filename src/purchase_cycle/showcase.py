"""Generators for the portfolio showcase: graph diagrams, the evaluation results table and the baseline comparison."""

import json
import re
import tempfile
from pathlib import Path

from purchase_cycle import config

GRAPHS_FILE = config.ROOT / "docs" / "graphs.md"

GRAPHS_HEADER = """# Graph diagrams

Generated by `uv run purchase-cycle diagrams` from the compiled LangGraph graphs with `get_graph().draw_mermaid()`.
No model is called and nothing here is edited by hand; a test fails when this file differs from the code.
"""


def _build_graphs(folder: Path) -> list[tuple[str, str, object]]:
    """Every graph of the project as (title, builder name, compiled graph); builders only wire nodes, so no client is needed."""
    from langgraph.checkpoint.memory import InMemorySaver

    from purchase_cycle import (
        claims,
        clarification,
        customer_responses,
        cycle,
        db,
        email_order,
        graph,
        quote_decision,
        quotes,
        receipts,
        reconciliation,
        sales,
        web_form,
        whatsapp_order,
    )

    db_path = folder / "business.db"
    conn = db.connect(db_path)
    db.seed(conn)
    conn.close()
    clients = clarification.ClarificationClients(None, None)
    folders = cycle.Folders(folder, folder, folder, folder)
    checkpointer = InMemorySaver()
    return [
        ("Orchestrator", "cycle.build_cycle_graph", cycle.build_cycle_graph(db_path, checkpointer, folders, None)),
        ("Order lines", "graph.build_graph", graph.build_graph(None, db_path)),
        ("Web form order", "web_form.build_web_form_graph", web_form.build_web_form_graph(None, db_path)),
        (
            "Email order",
            "email_order.build_email_order_graph",
            email_order.build_email_order_graph(None, None, db_path),
        ),
        (
            "WhatsApp order",
            "whatsapp_order.build_whatsapp_order_graph",
            whatsapp_order.build_whatsapp_order_graph(None, None, db_path, folder / "outbox"),
        ),
        (
            "Clarification",
            "clarification.build_clarification_graph",
            clarification.build_clarification_graph(clients, db_path, "web_form"),
        ),
        ("Quote requests", "quotes.build_quote_request_graph", quotes.build_quote_request_graph(db_path)),
        (
            "Quote decision",
            "quote_decision.build_quote_decision_graph",
            quote_decision.build_quote_decision_graph(db_path),
        ),
        (
            "Supplier reconciliation",
            "reconciliation.build_reconcile_graph",
            reconciliation.build_reconcile_graph(None, db_path),
        ),
        ("Supplier claim", "claims.build_claim_graph", claims.build_claim_graph(db_path)),
        (
            "Goods receipt",
            "receipts.build_receipt_graph",
            receipts.build_receipt_graph(db_path, folder / "notes"),
        ),
        (
            "Sales reconciliation",
            "sales.build_sales_graph",
            sales.build_sales_graph(db_path, folder / "invoices", folder / "inbox"),
        ),
        (
            "Customer response",
            "customer_responses.build_response_graph",
            customer_responses.build_response_graph(db_path),
        ),
    ]


def render_graphs() -> str:
    """The text of `docs/graphs.md`, built in memory from the compiled graphs."""
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp:
        built = _build_graphs(Path(tmp))
        parts = [GRAPHS_HEADER]
        for title, builder, compiled in built:
            diagram = compiled.get_graph().draw_mermaid().strip()
            parts.append(f"## {title}\n\nBuilt by `{builder}`.\n\n```mermaid\n{diagram}\n```\n")
    return "\n".join(parts)


def cmd_diagrams(args) -> int:
    GRAPHS_FILE.write_text(render_graphs(), encoding="utf-8", newline="\n")
    print(f"diagrams written to {GRAPHS_FILE}")
    return 0


RESULTS_START, RESULTS_END = "<!-- results-table:start -->", "<!-- results-table:end -->"


def _verdict(summary: dict) -> str:
    if summary.get("status") != "passed":
        return "FAIL"
    verdicts = {g["verdict"] for g in summary.get("gates", [])}
    return "PASS" if "PASS" in verdicts else "reported"


def results_table(directory: Path | None = None) -> str:
    """One Markdown table over the replayed summaries: cases, main metric with its 95% Wilson interval, gate verdict."""
    from purchase_cycle.evaluation.harness import ALL_SUITES, SUMMARIES_DIR

    directory = Path(directory) if directory else SUMMARIES_DIR
    rows = ["| Suite | Cases | Main metric | Value (95% Wilson) | Gate |", "|---|---|---|---|---|"]
    for name in ALL_SUITES:
        path = directory / f"{name}.json"
        try:
            summary = json.loads(path.read_text(encoding="utf-8"))
            metric = summary["metrics"][0]
        except (OSError, ValueError, KeyError, IndexError):
            rows.append(f"| {name} | - | - | - | missing |")
            continue
        interval = f" [{metric['ci_low']}, {metric['ci_high']}]" if metric.get("ci_low") is not None else ""
        rows.append(
            f"| {name} | {summary['case_count']} | {metric['name']} | {metric['value_text']}{interval} "
            f"| {_verdict(summary)} |"
        )
    return "\n".join(rows)


def marked_block(text: str, start: str, end: str) -> str | None:
    """The text between two README markers, without the surrounding blank lines; None when a marker is missing."""
    match = re.search(re.escape(start) + r"(.*?)" + re.escape(end), text, re.DOTALL)
    return match.group(1).strip() if match else None


def cmd_results_table(args) -> int:
    table = results_table(args.summaries)
    if not args.check:
        print(table)
        return 0
    block = marked_block(Path(args.check).read_text(encoding="utf-8"), RESULTS_START, RESULTS_END)
    if block == table:
        print(f"results table in {args.check} is up to date")
        return 0
    print(f"results table in {args.check} differs from the summaries; replace the block with:\n{table}")
    return 1


def add_showcase_commands(sub) -> None:
    sub.add_parser("diagrams", help="write docs/graphs.md with one Mermaid diagram per graph").set_defaults(
        handler=cmd_diagrams
    )
    results = sub.add_parser("results-table", help="print the evaluation results table from the summaries")
    results.add_argument("--summaries", default=None, help="folder of summary files (default data/eval_summaries)")
    results.add_argument("--check", metavar="FILE", help="exit 1 when the table between the markers of FILE differs")
    results.set_defaults(handler=cmd_results_table)
